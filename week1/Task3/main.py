# 1. Integer to float
num_int = 10
converted_float = float(num_int)
print("Integer to float:", converted_float, type(converted_float))


# 2. Float to integer
num_float = 10.75
converted_int = int(num_float)
print("Float to integer:", converted_int, type(converted_int))


# 3. Integer to string
num_to_str = str(42)
print("Integer to string:", num_to_str, type(num_to_str))


# 4. String to integer
str_num = "123"
str_converted_int = int(str_num)
print("String to integer:", str_converted_int, type(str_converted_int))


# 5. Integer to boolean
bool_val = bool(1)
print("Integer to boolean:", bool_val, type(bool_val))